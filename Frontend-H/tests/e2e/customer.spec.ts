import { loginApi, finishBrowserMfa } from './helpers'
import { test, expect } from '@playwright/test'

test.skip(process.env.E2E_ALLOW_WRITES!=='1','Requiere una demo aislada y E2E_ALLOW_WRITES=1')
const api=process.env.E2E_API_URL||'http://localhost:3300/api'
const customerEmail=process.env.E2E_CUSTOMER_EMAIL||'customer@hotel.com'
const customerPassword=process.env.E2E_CUSTOMER_PASSWORD||'Customer123!'

test('huésped: login, estancias propias, comprobante y bloqueo del panel interno',async({page,request})=>{
  const errors:string[]=[],diagnostics:string[]=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',entry=>{if(entry.type()==='error')diagnostics.push(entry.text())})
  await page.setViewportSize({width:390,height:844})
  await page.goto('/auth/login?redirect=/operations/calendar')
  await page.getByLabel('Correo electrónico',{exact:true}).fill(customerEmail)
  await page.getByLabel('Contraseña',{exact:true}).fill(customerPassword)
  await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();await finishBrowserMfa(page)
  await expect(page).toHaveURL(/\/portal$/)
  await expect(page.getByRole('heading',{name:/Hola, María/})).toBeVisible()
  await expect(page.getByRole('navigation',{name:'Navegación del huésped'})).toBeVisible()
  await expect(page.getByRole('link',{name:'Caja',exact:true})).toHaveCount(0)
  await expect(page.getByRole('link',{name:'Equipo',exact:true})).toHaveCount(0)
  const historical=page.getByRole('article').filter({hasText:'Finalizada'})
  await historical.getByRole('link',{name:'Ver detalles',exact:true}).click()
  await expect(page.getByRole('heading',{name:/Reserva #/})).toBeVisible()
  await page.getByRole('link',{name:'Ver comprobante',exact:true}).first().click()
  await expect(page.getByRole('heading',{name:'Mi comprobante'})).toBeVisible()
  await expect(page.getByText('María González',{exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Imprimir',exact:true})).toBeEnabled()
  await expect(page.getByText(/No válido como factura fiscal/)).toBeVisible()
  await page.goto('/dashboard')
  await expect(page).toHaveURL(/\/portal$/)
  await expect(page.getByRole('heading',{name:/Hola, María/})).toBeVisible()
  // La protección se comprueba también por HTTP, fuera de la navegación del frontend.
  const login=await loginApi(request,{email:customerEmail,password:customerPassword})
  const token=(await login.json()).data.token
  const denied=await request.get(`${api}/payments`,{headers:{Authorization:`Bearer ${token}`}})
  expect(denied.status()).toBe(403)
  const second=await loginApi(request,{email:'customer2@hotel.com',password:'Customer123!'})
  const secondToken=(await second.json()).data.token
  const others=await request.get(`${api}/portal/reservations`,{headers:{Authorization:`Bearer ${secondToken}`}})
  const foreignId=(await others.json()).data[0].id
  const rejected=page.waitForResponse(r=>r.url()===`${api}/portal/reservations/${foreignId}` && r.status()===404)
  await page.goto(`/portal/reservations/${foreignId}`)
  await expect(page.getByRole('alert')).toContainText('Reserva no encontrada')
  const failure=await rejected,requestId=failure.headers()['x-request-id']
  expect(requestId).toBeTruthy()
  expect((await failure.json()).requestId).toBe(requestId)
  await expect.poll(()=>diagnostics.some(message=>message.includes(`[${requestId}]`))).toBe(true)
  await expect(page.getByRole('heading',{name:/Habitación/})).toHaveCount(0)
  await page.getByRole('button',{name:'Cerrar sesión',exact:true}).click()
  await expect(page).toHaveURL(/\/auth\/login/)
  expect(errors).toEqual([])
})

