  const admin=await loginApi(request,{email:process.env.E2E_EMAIL||'admin@hotel.com',password:process.env.E2E_PASSWORD||'Admin123!'})
  const headers={Authorization:`Bearer ${(await admin.json()).data.token}`}
  const type=await request.post(`${api}/room-types`,{headers,data:{name:`Reserva web ${suffix}`,price:80,capacity:2}})
  expect(type.ok()).toBeTruthy()
  const room=await request.post(`${api}/rooms`,{headers,data:{number,room_type_id:(await type.json()).data.id,floor:1}})
  expect(room.ok()).toBeTruthy()
  await page.setViewportSize({width:390,height:844})
  await page.goto('/auth/login')
  await page.getByLabel('Correo electrónico',{exact:true}).fill(customerEmail)
  await page.getByLabel('Contraseña',{exact:true}).fill(customerPassword)
  await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();await finishBrowserMfa(page)
  await expect(page).toHaveURL(/\/portal$/)
  const skip=page.getByRole('link',{name:'Ir al contenido',exact:true})
  await expect(skip).not.toBeInViewport()
  await skip.focus()
  await expect(skip).toBeInViewport()
  await skip.press('Enter')
  await expect(page.locator('#guest-content')).toBeFocused()
  await page.getByRole('link',{name:'Nueva reserva',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Nueva reserva',exact:true})).toBeVisible()
  await page.getByLabel('Llegada',{exact:true}).fill('2035-11-01')
  await page.getByLabel('Salida',{exact:true}).fill('2035-11-03')
  await page.getByLabel('Adultos',{exact:true}).fill('1')
  await page.getByLabel('Niños',{exact:true}).fill('1')
  await page.getByRole('button',{name:'Consultar disponibilidad',exact:true}).click()
  await page.getByRole('radio',{name:`Seleccionar habitación ${number}`,exact:true}).check()
  await expect(page.getByText('Bs 160,00',{exact:true}).first()).toBeVisible()
  const completed=page.waitForResponse(r=>r.url()===`${api}/portal/reservations`&&r.request().method()==='POST')
  await page.getByLabel('Hora estimada de llegada (opcional)').fill('17:30')
  await page.getByLabel('Solicitudes especiales (opcional)').fill('Llegada con un niño, habitación tranquila si es posible')
  await page.getByRole('button',{name:'Confirmar reserva',exact:true}).click()
